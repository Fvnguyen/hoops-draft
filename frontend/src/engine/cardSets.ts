/**
 * Card sets by version (season_2026_27 D8/D9).
 *
 * The shipping set is `src/data/cards.json` (`CARD_SET_VERSION`). Every weekly refresh
 * freezes the previous set to `src/data/cardsets/<version>.json`; the four most recent
 * frozen sets are kept. A draft resume, an 82:0 run and a Playoffs match load the set
 * they started on through `loadCardSet`, so a refresh never changes a cube, an NBA
 * opponent or a pick mid-way. Frozen sets are dynamic imports: they never reach a bundle
 * unless a pinned object actually asks for one.
 *
 * `FROZEN_CARD_SETS` is rewritten by `data/refresh_season.py`; keep its shape.
 */

import { CARD_SET_VERSION } from './cardSetVersion';
import { getAllCards } from './cards';
import type { PlayerCardData } from './types';

/** The version every draft, roster and match without a stamp was made on. */
export const LEGACY_CARD_SET_VERSION = '2025-26.2';

// BEGIN FROZEN_CARD_SETS (generated by data/refresh_season.py)
const FROZEN_CARD_SETS: Record<string, () => Promise<{ default: unknown }>> = {
  '2025-26.2': () => import('@/data/cardsets/2025-26.2.json'),
};
// END FROZEN_CARD_SETS

/** A missing stamp means the legacy set (everything saved before stamps existed). */
export function resolveCardSetVersion(version: string | null | undefined): string {
  return version || LEGACY_CARD_SET_VERSION;
}

/** True when this build can still load `version`: the current set or a kept frozen one.
 *  False means the screen shows "Started on an older card set" with Abandon only (D9). */
export function isCardSetAvailable(version: string | null | undefined): boolean {
  const v = resolveCardSetVersion(version);
  return v === CARD_SET_VERSION || v in FROZEN_CARD_SETS;
}

const loaded = new Map<string, PlayerCardData[]>();

/** The cards of `version` (missing = legacy). Same array reference on every call for a
 *  version, so reference-keyed caches (`buildNbaTeams`) keep working. Throws for a
 *  version this build no longer carries; check `isCardSetAvailable` first. */
export async function loadCardSet(version: string | null | undefined): Promise<PlayerCardData[]> {
  const v = resolveCardSetVersion(version);
  if (v === CARD_SET_VERSION) return getAllCards();
  const hit = loaded.get(v);
  if (hit) return hit;
  const load = FROZEN_CARD_SETS[v];
  if (!load) throw new Error(`Card set ${v} is no longer available`);
  const cards = (await load()).default as PlayerCardData[];
  loaded.set(v, cards);
  return cards;
}

/** Versions this build can load, current first. */
export function availableCardSetVersions(): string[] {
  return [CARD_SET_VERSION, ...Object.keys(FROZEN_CARD_SETS)];
}
